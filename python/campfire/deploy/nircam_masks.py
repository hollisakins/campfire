"""
DS9 ``.reg`` rendering of portal mask polygons (``mask_regions`` JSONB).

The portal's mask editors (NIRCam exposures, ``/admin/nircam/[id]``; NIRSpec rate
files) store polygons as DS9 ``image`` coordinates, 1-indexed. The reduction reads
them as ``.reg`` files written here: NIRCam masks are synced by the config plane
(``nircam_review``, ``campfire config pull --masks``), NIRSpec rate masks by
``nirspec_masks.pull_rate_masks``.

Why pixel coords as the canonical DB representation:
    The web canvas is pixel-native and cannot reasonably ship a GWCS-aware
    JS WCS library. Polygons were converted FK5/ICRS → pixel once at import
    time using the actual exposure WCS (with distortion), so the in-browser
    editor can render and edit polygons with zero WCS round-trips, and
    ``apply_masks_step`` reads the materialized ``image``-coord ``.reg``
    as a no-op pixel polygon.
"""

from datetime import datetime, timezone

_LOCAL_FIRST_NOTE = '# Local edits are kept: a pull never overwrites an existing file.'


def _utcnow_iso():
    return datetime.now(timezone.utc).isoformat()


def _serialize_regfile(polygons, generated_at, *, written_by='campfire deploy pull-masks',
                       note=_LOCAL_FIRST_NOTE):
    """Render a list of polygon dicts as a DS9 image-coord .reg file.

    Comment lines (``written_by``, ``note``) are not part of the mask: the
    pipelines hash only the region lines, so a rewrite with a new timestamp is
    not a mask change."""
    lines = [
        '# Region file format: DS9 version 4.1',
        f'# Generated by {written_by} at {generated_at}.',
        note,
        ('global color=green dashlist=8 3 width=1 font="helvetica 10 normal '
         'roman" select=1 highlite=1 dash=0 fixed=0 edit=1 move=1 delete=1 '
         'include=1 source=1'),
        'image',
    ]
    for poly in polygons:
        verts = poly.get('vertices') or []
        if len(verts) < 3:
            continue
        flat = ','.join(f'{float(x):.4f},{float(y):.4f}' for x, y in verts)
        label = poly.get('label')
        suffix = f' # text={{{label}}}' if label else ''
        lines.append(f'polygon({flat}){suffix}')
    return '\n'.join(lines) + '\n'

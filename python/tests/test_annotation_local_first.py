"""local_first: annotation pulls never overwrite local config."""
from campfire.deploy.local_first import KEPT_LOCAL, UNCHANGED, WRITTEN, write_if_absent


def test_write_if_absent(tmp_path):
    p = tmp_path / 'a.reg'
    assert write_if_absent(p, '# hdr 1\nimage\npolygon(1,2,3)\n') == WRITTEN
    # same content lines, different comment header: identical, file left alone
    assert write_if_absent(p, '# hdr 2\nimage\npolygon(1,2,3)\n') == UNCHANGED
    assert p.read_text().startswith('# hdr 1')
    # different polygons: the local file wins
    assert write_if_absent(p, 'image\npolygon(9,9,9)\n') == KEPT_LOCAL
    assert 'polygon(1,2,3)' in p.read_text()


def _generated(body):
    """A region file as cfpipe's HST trails step writes it: the hash of its own
    content lines in the header."""
    import hashlib
    from campfire.deploy.local_first import GENERATED_HASH_MARK, body_lines
    digest = hashlib.sha256('\n'.join(body_lines(body)).encode()).hexdigest()[:16]
    return f'# Generated by cfpipe acswfc trails\n{GENERATED_HASH_MARK} {digest}\n{body}'


def test_an_unedited_pipeline_mask_gives_way_to_the_portals(tmp_path):
    """A satellite-trail mask the pipeline wrote is a first guess: once a
    reviewer has changed it in the portal, a pull brings that version down.
    A mask anyone edited by hand is local configuration and stays."""
    from campfire.deploy.local_first import REPLACED, is_unedited_generated

    portal = '# pulled\nimage\npolygon(5,5,6,6,7,7) # text={satellite trail}\n'
    p = tmp_path / 'j8pu6eicq_flc.reg'
    p.write_text(_generated('image\npolygon(1,2,3,4,5,6) # text={satellite trail}\n'))
    assert is_unedited_generated(p.read_text())
    # the ordinary pull rule still keeps it
    assert write_if_absent(p, portal) == KEPT_LOCAL
    # a dry run reports the replacement and leaves the file
    assert write_if_absent(p, portal, replace_unedited=True, dry_run=True) == REPLACED
    assert 'polygon(1,2,3,4,5,6)' in p.read_text()
    assert write_if_absent(p, portal, replace_unedited=True) == REPLACED
    assert p.read_text() == portal
    # what was pulled is not a pipeline file: a later, different pull keeps it
    assert write_if_absent(p, 'image\npolygon(9,9,9,8,8,8)\n',
                           replace_unedited=True) == KEPT_LOCAL

    # edited by hand after the pipeline wrote it: the hash no longer matches
    q = tmp_path / 'j8pu6eigq_flc.reg'
    q.write_text(_generated('image\npolygon(1,2,3,4,5,6)\n').replace('1,2,3', '1,2,4'))
    assert not is_unedited_generated(q.read_text())
    assert write_if_absent(q, portal, replace_unedited=True) == KEPT_LOCAL
    # a hand-drawn file never had the line
    assert not is_unedited_generated('image\nbox(1,2,3,4,0)\n')


def test_the_pipeline_and_the_client_hash_a_region_file_alike(tmp_path):
    """The trails step (campfire_pipeline) writes the hash; the client reads it.
    Neither imports the other, so this pins the two implementations together."""
    import pytest
    trails = pytest.importorskip('campfire_pipeline.hst.steps.trails')
    from campfire.deploy.local_first import (
        GENERATED_HASH_MARK, is_unedited_generated,
    )

    assert trails.HASH_MARK == GENERATED_HASH_MARK
    text = trails.region_text([[[0.0, 1.0], [5.0, 1.0], [5.0, 3.0]]], 'acswfc')
    assert is_unedited_generated(text) and trails.is_unedited_trail_file(text)
    edited = text.replace('6.00,2.00', '6.50,2.00')
    assert edited != text
    assert not is_unedited_generated(edited) and not trails.is_unedited_trail_file(edited)


def test_write_if_absent_dry_run(tmp_path):
    p = tmp_path / 'b.reg'
    assert write_if_absent(p, 'image\n', dry_run=True) == WRITTEN
    assert not p.exists()

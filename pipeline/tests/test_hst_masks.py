def test_a_trail_is_a_band_cut_to_the_chip():
    pytest.importorskip('shapely')
    # a horizontal trail along row 20 of a 80 x 120 chip, 3 pixels to each side
    poly = np.array(trails.trail_polygon((10.0, 20.0), (60.0, 20.0), 3.0, (80, 120)))
    assert poly[:, 0].min() == -0.5 and poly[:, 0].max() == 119.5   # chip edges
    assert poly[:, 1].min() == 17.0 and poly[:, 1].max() == 23.0
    # a diagonal one is cut by the chip's box, so it has more than four corners
    diag = np.array(trails.trail_polygon((0.0, 0.0), (79.0, 79.0), 5.0, (80, 120)))
    assert len(diag) > 4
    assert diag[:, 1].max() <= 79.5 and diag[:, 0].min() >= -0.5
    # a band that misses the chip is no polygon
    assert trails.trail_polygon((0.0, 500.0), (100.0, 500.0), 3.0, (80, 120)) is None


def _fake_finder(found):
    """A stand-in for chip_trails: ``found[extver]`` is the list of trails."""
    def chip_trails(exposure_file, extver, params, processes=1):
        return found[extver]
    return chip_trails


def _trail(snr, persistence, polygon=None):
    t = {'snr': snr, 'persistence': persistence, 'width': 12.0, 'theta': 55.0,
         'accepted': polygon is not None}
    if polygon is not None:
        t['polygon'] = polygon
    return t


_BAND = [[-0.5, 2.0], [31.5, 2.0], [31.5, 4.0], [-0.5, 4.0]]     # rows 2.5 to 3.5


def test_trails_go_into_the_exposures_region_file(tmp_path, monkeypatch):
    """A trail found on the upper chip is a polygon in the frame of the
    stacked preview; apply_masks then masks it like a hand-drawn region."""
    pytest.importorskip('regions')
    path = str(tmp_path / 'jtest01aaq_flc.fits')
    ny, nx, _t, _sky = _acs_file(path)                   # 24 x 32 per chip
    reg = str(tmp_path / 'masks' / 'f606w' / 'jtest01aaq_flc.reg')
    before = {v: fits.getdata(path, ('DQ', v)).copy() for v in (1, 2)}
    found = {1: [_trail(6.0, 0.6)], 2: [_trail(280.0, 1.0, _BAND)]}
    monkeypatch.setattr(trails, 'chip_trails', _fake_finder(found))

    result = trails.trails_step(path, reg)
    assert [t['accepted'] for t in result[2]] == [True]
    text = open(reg).read()
    assert 'Generated by cfpipe acswfc trails' in text
    assert trails.is_unedited_trail_file(text)
    # DS9 readers split lines on ';', comments included
    assert ';' not in text
    from regions import Regions
    import warnings as _warnings
    with _warnings.catch_warnings():
        _warnings.simplefilter('error')
        assert len(Regions.read(reg)) == 1
    (line,) = [ln for ln in text.splitlines() if ln.startswith('polygon')]
    assert line.endswith('# text={satellite trail}')
    # DS9 image coordinates are 1-based, and the upper chip starts at row 24
    assert line.startswith('polygon(0.50,27.00,32.50,27.00,32.50,29.00,0.50,29.00)')
    with fits.open(path) as hdul:                        # pixels and DQ untouched
        assert all(np.array_equal(hdul['DQ', v].data, before[v]) for v in (1, 2))
        assert hdul[0].header['CFP_TRL'] == 'findsat n=1 reg=written'
    assert trails.trails_step(path, reg) is None         # stamped: nothing to do

    assert apply_masks.apply_masks_step(path, reg) == 2 * nx
    with fits.open(path) as hdul:
        assert hdul[MASK_EXT, 1].data.sum() == 0
        assert hdul[MASK_EXT, 2].data[2:4].all()
    assert not open_exposure(path)[1].load().good[2:4].any()


def test_the_step_never_replaces_a_file_that_is_somebodys(tmp_path, monkeypatch):
    path = str(tmp_path / 'jtest01aaq_flc.fits')
    _acs_file(path)
    reg = str(tmp_path / 'masks' / 'jtest01aaq_flc.reg')
    found = {1: [_trail(50.0, 1.0, _BAND)], 2: []}
    monkeypatch.setattr(trails, 'chip_trails', _fake_finder(found))

    # its own unedited file is replaced on a re-run
    trails.trails_step(path, reg)
    first = open(reg).read()
    found[1] = [_trail(50.0, 1.0, [[0, 5], [31, 5], [31, 9], [0, 9]])]
    trails.trails_step(path, reg, overwrite=True)
    assert open(reg).read() != first
    assert trails.is_unedited_trail_file(open(reg).read())

    # a reviewer edits it (drops a vertex): from then on it is theirs
    edited = open(reg).read().replace('1.00,6.00,', '')
    assert edited != open(reg).read()
    with open(reg, 'w') as f:
        f.write(edited)
    assert not trails.is_unedited_trail_file(edited)
    trails.trails_step(path, reg, overwrite=True)
    assert open(reg).read() == edited
    assert fits.getheader(path)['CFP_TRL'] == 'findsat n=1 reg=kept'

    # a hand-drawn file is left alone as well, and so is one when no trail is found
    with open(reg, 'w') as f:
        f.write('# Region file format: DS9\nimage\nbox(5,5,2,2,0)\n')
    found[1] = []
    trails.trails_step(path, reg, overwrite=True)
    assert 'box(5,5,2,2,0)' in open(reg).read()
    assert fits.getheader(path)['CFP_TRL'] == 'findsat n=0 reg=none'


def test_a_rerun_that_finds_nothing_removes_its_own_file(tmp_path, monkeypatch):
    path = str(tmp_path / 'jtest01aaq_flc.fits')
    _acs_file(path)
    reg = str(tmp_path / 'masks' / 'jtest01aaq_flc.reg')
    found = {1: [_trail(50.0, 1.0, _BAND)], 2: []}
    monkeypatch.setattr(trails, 'chip_trails', _fake_finder(found))
    trails.trails_step(path, reg)
    assert os.path.exists(reg)
    found[1] = []
    trails.trails_step(path, reg, overwrite=True)
    assert not os.path.exists(reg)
    assert fits.getheader(path)['CFP_TRL'] == 'findsat n=0 reg=removed'


def test_trails_is_an_acs_step(tmp_path):
    path = str(tmp_path / 'itest01aaq_flt.fits')
    primary = fits.PrimaryHDU()
    primary.header.update({'INSTRUME': 'WFC3', 'DETECTOR': 'IR'})
    primary.writeto(path)
    with pytest.raises(ValueError, match='ACS/WFC'):
        trails.trails_step(path, str(tmp_path / 'x.reg'))
    assert 'trails' in [n for n, _ in orchestrate.steps_for('acswfc')]
    assert 'trails' not in [n for n, _ in orchestrate.steps_for('wfc3ir')]
    # the cuts ship in the config, nowhere else
    cfg = get_hst_step_config('trails', 'acswfc')
    assert cfg['min_persistence'] == 0.8 and cfg['min_snr'] == 8.0
    assert cfg['grow'] == 12 and 'ignore' not in cfg
    assert get_hst_step_config('trails', 'wfc3ir') == {}


def test_only_confident_trails_become_polygons(tmp_path, monkeypatch):
    """The finder's catalog holds a strong trail, a weak one that passed its
    own cuts, and a rejected candidate: only the first gets a polygon."""
    findsat = pytest.importorskip('acstools.findsat_mrt')
    from astropy.table import Table

    path = str(tmp_path / 'jtest01aaq_flc.fits')
    hdul = fits.HDUList([fits.PrimaryHDU()])
    for v in (1, 2):
        for name, dtype in (('SCI', 'float32'), ('ERR', 'float32'), ('DQ', 'int16')):
            hdul.append(fits.ImageHDU(np.zeros((80, 120), dtype), name=name, ver=v))
    hdul.writeto(path)

    class Finder:
        def __init__(self, image_file, extension=None, binsize=None, **kw):
            assert extension == 1 and binsize == 2
            assert kw['min_persistence'] == 0.8 and kw['threshold'] == 5.0
            self.image = np.zeros((40, 60))
            self.source_list = Table({
                'id': [1, 2, 3], 'status': [2, 2, 0],
                'snr': [50.0, 6.0, 30.0], 'persistence': [1.0, 0.9, 0.0],
                'width': [4.0, 4.0, 4.0], 'theta': [90.0, 0.0, 45.0],
                'endpoints': [[(0.0, 20.0), (59.0, 20.0)],
                              [(30.0, 0.0), (30.0, 39.0)],
                              [(0.0, 0.0), (39.0, 39.0)]],
            })

        def run_mrt(self):
            pass

        find_mrt_sources = filter_sources = run_mrt

    monkeypatch.setattr(findsat, 'WfcWrapper', Finder)
    params = dict(get_hst_step_config('trails', 'acswfc'), grow=0)
    found = trails.chip_trails(path, 1, params)
    assert [(t['snr'], t['accepted']) for t in found] == [(50.0, True), (6.0, False)]
    assert found[0]['width'] == 8.0                 # binned pixels -> native
    assert 'polygon' not in found[1]
    poly = np.array(found[0]['polygon'])
    # binned row 20 is native rows 40 and 41: centre 40.5, half-width 4
    assert poly[:, 1].min() == 36.5 and poly[:, 1].max() == 44.5
    assert poly[:, 0].min() == -0.5 and poly[:, 0].max() == 119.5
    grown = np.array(trails.chip_trails(path, 1, dict(params, grow=3))[0]['polygon'])
    assert grown[:, 1].min() == 33.5 and grown[:, 1].max() == 47.5



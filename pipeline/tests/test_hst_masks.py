"""What keeps pixels out of an HST mosaic besides cosmic rays: the region files
of an exposure (hand-drawn masks, and the satellite trails the ``trails`` step
writes into the same files), and the review previews they are drawn on.

The trail finder itself (acstools.findsat_mrt) is exercised on real exposures
(docs/hst/design.md, section 8b); here its catalog is replaced by a fixed one,
and what the step does with it is checked.
"""


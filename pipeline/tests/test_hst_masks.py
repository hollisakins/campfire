# What `campfire pull` writes for an exposure whose pipeline-found mask a
# reviewer deleted in the portal (campfire.deploy.nircam_masks, the serializer
# given no polygons): a region file with no region in it.
_REVIEWED_NO_MASK = (
    '# Region file format: DS9 version 4.1\n'
    '# Generated by campfire deploy pull-masks at 2026-11-16T00:00:00+00:00.\n'
    '# Local edits are kept: a pull never overwrites an existing file.\n'
    'global color=green dashlist=8 3 width=1 font="helvetica 10 normal roman" '
    'select=1 highlite=1 dash=0 fixed=0 edit=1 move=1 delete=1 include=1 source=1\n'
    'image\n'
)


def test_a_mask_removed_in_review_stays_removed(tmp_path, monkeypatch):
    """The trail step finds the trail again on every run. Once a reviewer has
    said the exposure needs no mask, the step must not put one back, and the
    mask already applied must come off."""
    pytest.importorskip('regions')
    path = str(tmp_path / 'jtest01aaq_flc.fits')
    _acs_file(path)
    reg = str(tmp_path / 'masks' / 'jtest01aaq_flc.reg')
    monkeypatch.setattr(trails, 'chip_trails',
                        _fake_finder({1: [_trail(50.0, 1.0, _BAND)], 2: []}))

    trails.trails_step(path, reg)
    assert apply_masks.apply_masks_step(path, reg) > 0

    with open(reg, 'w') as f:                       # the pull's answer
        f.write(_REVIEWED_NO_MASK)
    assert not trails.is_unedited_trail_file(_REVIEWED_NO_MASK)
    trails.trails_step(path, reg, overwrite=True)
    assert open(reg).read() == _REVIEWED_NO_MASK
    assert fits.getheader(path)['CFP_TRL'] == 'findsat n=1 reg=kept'

    assert not apply_masks.is_current(path, reg)
    assert apply_masks.apply_masks_step(path, reg) == 0
    with fits.open(path) as hdul:
        assert sum(int(h.data.sum()) for h in hdul if h.name == MASK_EXT) == 0



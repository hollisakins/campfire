-- Multi-instrument imaging: `nircam_exposures` becomes `exposures`.
--
-- The per-exposure review table (review queue, preview keys, reviewer masks
-- and exclusions) now holds every imaging instrument: NIRCam and the HST
-- instruments ACS/WFC and WFC3/IR. Hand-authored on purpose, as
-- 20261026104159_phase2b_rename_measurement_tables.sql was: pg-delta has no
-- rename and would express this as DROP + CREATE, which loses every row and
-- with them the reviewers' decisions and masks. Everything here is a catalog
-- rename (ALTER ... RENAME), so no data moves and the dependent objects
-- (policies, grants, the column default on the sequence) follow by OID.
--
--   nircam_exposures                  -> exposures
--   nircam_exposures_id_seq           -> exposures_id_seq
--   nircam_exposures_pkey             -> exposures_pkey
--   nircam_exposures_unique           -> exposures_unique
--   idx_nircam_exposures_field_filter -> idx_exposures_field_filter
--   idx_nircam_exposures_review       -> idx_exposures_review
--
-- What a rename cannot carry is in the companion migration generated by
-- `declarative sync` right after this one: the new `instrument` column and
-- its place in the row identity, the progress view (which reads the column),
-- and the function bodies, which are text and name the table.
--
-- Between this migration and the web image that reads `exposures`, the admin
-- exposure pages of the previous image fail (they name the old table). They
-- are admin-only; the window is the deploy's own.

ALTER TABLE public.nircam_exposures RENAME TO exposures;
ALTER SEQUENCE public.nircam_exposures_id_seq RENAME TO exposures_id_seq;

-- Constraints (a PRIMARY KEY / UNIQUE rename renames its index too)
ALTER TABLE public.exposures RENAME CONSTRAINT nircam_exposures_pkey TO exposures_pkey;
ALTER TABLE public.exposures RENAME CONSTRAINT nircam_exposures_unique TO exposures_unique;

-- Indexes
ALTER INDEX public.idx_nircam_exposures_field_filter RENAME TO idx_exposures_field_filter;
ALTER INDEX public.idx_nircam_exposures_review RENAME TO idx_exposures_review;

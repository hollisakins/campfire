-- Multi-instrument imaging: `nircam_images` becomes `mosaics`.
--
-- The mosaic index now holds every imaging instrument: NIRCam and the HST
-- instruments ACS/WFC and WFC3/IR, drizzled onto the same tiles. Hand-authored
-- on purpose, as 20261116210000_exposures_rename.sql and
-- 20261026104159_phase2b_rename_measurement_tables.sql were: pg-delta has no
-- rename and would express this as DROP + CREATE, which loses every row (the
-- live index and the frozen copies of every data release). Everything in the
-- first part is a catalog rename (ALTER ... RENAME), so no data moves and the
-- dependent objects (grants, the column default on the sequence, the policy
-- bodies) follow by OID.
--
--   nircam_images                     -> mosaics
--   nircam_images_id_seq              -> mosaics_id_seq
--   nircam_images_pkey                -> mosaics_pkey
--   nircam_images_unique              -> mosaics_unique
--   nircam_images_deployment_id_fkey  -> mosaics_deployment_id_fkey
--   nircam_images_deploy_status_check -> mosaics_deploy_status_check
--   idx_images_field / idx_images_filter -> idx_mosaics_field / idx_mosaics_filter
--   dr_nircam_images                  -> dr_mosaics
--   dr_nircam_images_pkey             -> dr_mosaics_pkey
--   idx_dr_nircam_images_tag_field    -> idx_dr_mosaics_tag_field
--   cat_nircam_images                 -> cat_mosaics
--   policies: authenticated_select_nircam / admin_insert_nircam /
--             admin_update_nircam / reader_select_nircam_images
--                                     -> *_mosaics
--             select_dr_nircam_images / reader_select_dr_nircam_images
--                                     -> *_dr_mosaics
--
-- What a rename cannot carry is in the companion migration generated by
-- `declarative sync` right after this one: the `instrument` column on both
-- tables and its place in the live row's identity, the view's new column, and
-- the function bodies, which are text and name the tables.
--
-- The wire formats keep their keys, as in the phase 2b rename: the release
-- `counts.nircam_images`, the readiness report's `drafts.nircam_images` and
-- the `nircam_images` block set_deployment_status returns.
--
-- Two things do change for callers, both on purpose:
--   * the read-only SQL role (docs/reader-role.md) reads `mosaics` and
--     `dr_mosaics`; the old names are gone, with no compatibility view;
--   * between this migration and the web image that reads `mosaics`, the
--     imaging pages of the previous image fail (they name the old table).
--     The window is the deploy's own.
--
-- The second part gives field deployments their instrument. One deploy is one
-- instrument's products of a field, so `deployments.instrument` is what tells
-- a field's NIRCam deployment from its HST ones. Every field deployment that
-- exists is NIRCam's; `deployments` is a small table (one row per deploy), so
-- the backfill is a single statement here. The check constraint and the
-- trigger that fills the column for writers that predate it come with the
-- generated companion.

-- Tables, sequence, view
ALTER TABLE public.nircam_images RENAME TO mosaics;
ALTER SEQUENCE public.nircam_images_id_seq RENAME TO mosaics_id_seq;
ALTER TABLE public.dr_nircam_images RENAME TO dr_mosaics;
ALTER VIEW public.cat_nircam_images RENAME TO cat_mosaics;

-- Constraints (a PRIMARY KEY / UNIQUE rename renames its index too)
ALTER TABLE public.mosaics RENAME CONSTRAINT nircam_images_pkey TO mosaics_pkey;
ALTER TABLE public.mosaics RENAME CONSTRAINT nircam_images_unique TO mosaics_unique;
ALTER TABLE public.mosaics RENAME CONSTRAINT nircam_images_deployment_id_fkey TO mosaics_deployment_id_fkey;
ALTER TABLE public.mosaics RENAME CONSTRAINT nircam_images_deploy_status_check TO mosaics_deploy_status_check;
ALTER TABLE public.dr_mosaics RENAME CONSTRAINT dr_nircam_images_pkey TO dr_mosaics_pkey;

-- Indexes
ALTER INDEX public.idx_images_field RENAME TO idx_mosaics_field;
ALTER INDEX public.idx_images_filter RENAME TO idx_mosaics_filter;
ALTER INDEX public.idx_dr_nircam_images_tag_field RENAME TO idx_dr_mosaics_tag_field;

-- Policies
ALTER POLICY "authenticated_select_nircam" ON public.mosaics RENAME TO "authenticated_select_mosaics";
ALTER POLICY "admin_insert_nircam" ON public.mosaics RENAME TO "admin_insert_mosaics";
ALTER POLICY "admin_update_nircam" ON public.mosaics RENAME TO "admin_update_mosaics";
ALTER POLICY "reader_select_nircam_images" ON public.mosaics RENAME TO "reader_select_mosaics";
ALTER POLICY "select_dr_nircam_images" ON public.dr_mosaics RENAME TO "select_dr_mosaics";
ALTER POLICY "reader_select_dr_nircam_images" ON public.dr_mosaics RENAME TO "reader_select_dr_mosaics";

-- Field deployments carry their imaging instrument
ALTER TABLE public.deployments ADD COLUMN instrument text;
UPDATE public.deployments SET instrument = 'nircam' WHERE field IS NOT NULL;

-- The registry admits the HST instruments. Two CHECKs on storage_objects
-- track the layout contract (campfire_layout): the instrument tokens and the
-- product types. 20261116200000 added the HST product types but left the
-- instrument check at nirspec | nircam, so the first HST file a deploy
-- registered would have been refused (23514) after its bytes were uploaded;
-- and the HST mosaics now have their own thumbnail and quick-look kinds, as
-- NIRCam's do. Here rather than in the generated companion, in the form the
-- earlier product-type migrations use: NOT VALID then VALIDATE. Each new
-- constraint admits every row the old one did, and validating separately
-- scans the (large) table under a SHARE UPDATE EXCLUSIVE lock only.
ALTER TABLE public.storage_objects DROP CONSTRAINT storage_objects_instrument_check;
ALTER TABLE public.storage_objects ADD CONSTRAINT storage_objects_instrument_check
  CHECK (((instrument IS NULL) OR (instrument = ANY (ARRAY['nirspec'::text, 'nircam'::text, 'acswfc'::text, 'wfc3ir'::text])))) NOT VALID;
ALTER TABLE public.storage_objects VALIDATE CONSTRAINT storage_objects_instrument_check;

ALTER TABLE public.storage_objects DROP CONSTRAINT storage_objects_product_type_check;
ALTER TABLE public.storage_objects ADD CONSTRAINT storage_objects_product_type_check
  CHECK ((product_type = ANY (ARRAY['nirspec_spec'::text, 'spectrum_json'::text, 'spectrum_1d_json'::text, 'zfit'::text, 'nirspec_lines'::text, 'nirspec_lines_json'::text, 'nirspec_redshifts'::text, 'nirspec_spectrum_exposure'::text, 'nirspec_rate'::text, 'rgb'::text, 'sed'::text, 'nircam_exposure'::text, 'nircam_exposure_preview'::text, 'nircam_exposure_full'::text, 'nircam_mosaic'::text, 'nircam_rgb'::text, 'nircam_expmap'::text, 'nircam_expmap_plot'::text, 'nircam_mosaic_thumbnail'::text, 'nircam_mosaic_quicklook'::text, 'nircam_layout'::text, 'tile'::text, 'photometry_pz'::text, 'nirspec_manual_mask'::text, 'nirspec_stuck_shutters'::text, 'nirspec_bkg_override'::text, 'nircam_mask'::text, 'nircam_astrom_cat'::text, 'nircam_bad_pixel'::text, 'nircam_flat'::text, 'nircam_wisp'::text, 'acswfc_exposure'::text, 'acswfc_exposure_preview'::text, 'acswfc_exposure_full'::text, 'acswfc_mosaic'::text, 'acswfc_mask'::text, 'acswfc_mosaic_thumbnail'::text, 'acswfc_mosaic_quicklook'::text, 'wfc3ir_exposure'::text, 'wfc3ir_exposure_preview'::text, 'wfc3ir_exposure_full'::text, 'wfc3ir_mosaic'::text, 'wfc3ir_mask'::text, 'wfc3ir_mosaic_thumbnail'::text, 'wfc3ir_mosaic_quicklook'::text]))) NOT VALID;
ALTER TABLE public.storage_objects VALIDATE CONSTRAINT storage_objects_product_type_check;

-- Deploy lease + data-release readiness (data releases P1, docs/design-data-
-- releases-impl-plan.md §3 "deploy lease" / "readiness RPC").
--   * deploy_scope_state gains four nullable lease columns (in_progress_since /
--     in_progress_by / in_progress_host / heartbeat_at); no backfill.
--   * begin_deploy_scope / heartbeat_deploy_scope / release_deploy_scope are new
--     SECURITY DEFINER RPCs (admin-or-service-role guard, search_path pinned,
--     revoked from PUBLIC and anon). begin bumps the scope version and returns
--     it as the holder's ownership token; heartbeat / release take p_version
--     and refuse an outdated token; claim_deploy_scope (unchanged signature)
--     CASes on it and clears the lease when it succeeds; deploy_lease_ttl() is
--     the shared 30-minute liveness window.
--   * dr_readiness() returns the stage-1 readiness numbers as one jsonb
--     (`campfire dr status`); statement_timeout 120 s like the sync RPCs.
-- Generated by `supabase db schema declarative sync` (CLI 2.120.0, pg-delta);
-- header added by hand per the migration convention.
